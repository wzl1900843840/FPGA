"""Regenerate only the 22 fixed 16x16 emergency glyph constants in the OSD."""
from pathlib import Path
import subprocess,sys
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
CHARS='正在呼叫请求已接收通信未确认告警解除保持冷静'

def main():
    target=ROOT/'src/user_source/rtl/promax_text_overlay.v'
    source=target.read_text(encoding='utf-8')
    font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',14)
    lines=['    // BEGIN FIXED EMERGENCY GLYPHS (generated by tools/generate_emergency_glyphs.py)']
    for index,char in enumerate(CHARS,9):
        im=Image.new('1',(16,16));draw=ImageDraw.Draw(im)
        box=draw.textbbox((0,0),char,font=font)
        draw.text(((16-(box[2]-box[0]))//2-box[0],(16-(box[3]-box[1]))//2-box[1]),char,font=font,fill=1)
        bits=''.join(str(int(im.getpixel((x,y))!=0)) for y in range(16) for x in range(16))
        lines.append(f"    localparam [255:0] CN_GLYPH_{index} = 256'h{int(bits,2):064x}; // {char}")
    lines.append('    // END FIXED EMERGENCY GLYPHS')
    block='\n'.join(lines)+'\n\n'
    if '// BEGIN FIXED EMERGENCY GLYPHS' in source:
        start=source.index('    // BEGIN FIXED EMERGENCY GLYPHS');end=source.index('    function [15:0] chinese_glyph_row;',start)
        source=source[:start]+block+source[end:]
    else:
        source=source.replace('    function [15:0] chinese_glyph_row;',block+'    function [15:0] chinese_glyph_row;')
        case='\n'.join(f"                5'd{i}: glyph_bits = CN_GLYPH_{i};" for i in range(9,31))
        source=source.replace("                default: glyph_bits = 256'b0;",case+"\n                default: glyph_bits = 256'b0;")
    target.write_text(source,encoding='utf-8')
    # Keep the sparse lookup in step with regenerated bitmap constants.
    subprocess.run([sys.executable,str(ROOT/'tools/compact_chinese_lookup.py')],check=True)
    print('Generated 22 fixed glyphs; existing subtitle IDs 0..8 preserved')

if __name__=='__main__':main()
